"""`burton ingest`: EPUB -> data/text/<unit>.xml, validated, with permanent ids."""

import hashlib
import json
import unicodedata
from collections import Counter

from lxml import etree

from .. import paths
from ..ids import Registry
from ..source import check_lock, read_lock
from ..tei import ED, XML_ID, XML_LANG, T, el, local, xml_id
from . import convert, epub, gowland, langid, manual


def fingerprint(e) -> str:
    text = " ".join(unicodedata.normalize("NFC", "".join(e.itertext())).split())
    return hashlib.sha1(text.encode()).hexdigest()[:12]


def assign_ids(div, unit: str, reg: Registry) -> Counter:
    counts: Counter = Counter()
    div.set(XML_ID, xml_id(unit))  # unit ids are the structural key itself

    def give(e, kind: str, locator: str, fp: str = "") -> None:
        e.set(XML_ID, xml_id(reg.assign(unit, kind, locator, fp)))
        counts[kind] += 1

    for p in div.iter(T("p")):
        if p.getparent().tag != T("note"):
            give(p, "p", p.get("src") or f"p@{counts['p']}")
    for i, lg in enumerate(div.iter(T("lg"))):
        first = lg.find(T("l"))
        give(lg, "lg", (first.get("src") if first is not None else None) or f"lg@{i}")
    for n in div.iter(T("note")):
        give(n, "n", n.get("src"))
    # foreign passages: located by their nearest ancestor with a src, plus occurrence order there
    seen: Counter = Counter()
    for f in div.iter():
        if not isinstance(f.tag, str) or f.get("ana") != "foreign":
            continue
        anc = f
        while anc is not None and not anc.get("src"):
            anc = anc.getparent()
        base = anc.get("src") if anc is not None else unit
        fp = fingerprint(f)
        seen[(base, fp)] += 1  # nth passage with this same text in this container (normally 1)
        give(f, "f", f"{base}|{fp}|{seen[(base, fp)]}", fp)
    return counts


def link_translations(div) -> None:
    """ed:trans@for points to the foreign passage it directly follows, where there is one."""
    for t in div.iter(ED("trans"), ED("verse-trans")):
        prev = t.getprevious()
        if prev is None:
            continue
        between = (prev.tail or "").strip(" ,;:.")
        if between == "" and (local(prev.tag) == "foreign" or prev.get("ana") == "foreign"):
            t.set("for", prev.get(XML_ID))


def wrap_document(div, unit: str, file: str):
    lock = read_lock()
    tei = el("TEI")
    tei.set(XML_LANG, "en")
    header = etree.SubElement(tei, T("teiHeader"))
    fd = etree.SubElement(header, T("fileDesc"))
    ts = etree.SubElement(fd, T("titleStmt"))
    etree.SubElement(ts, T("title")).text = f"The Anatomy of Melancholy, {unit}"
    ps = etree.SubElement(fd, T("publicationStmt"))
    etree.SubElement(ps, T("p")).text = "Generated by `burton ingest`. Do not edit by hand."
    sd = etree.SubElement(fd, T("sourceDesc"))
    etree.SubElement(sd, T("p")).text = (
        f"Gowland 2021 EPUB, sha256 {lock.get(paths.EPUB_COPY.name, '?')}, file {file}.xhtml"
    )
    text = etree.SubElement(tei, T("text"))
    body = etree.SubElement(text, T("body"))
    body.append(div)
    return etree.ElementTree(tei)


def validate(tree) -> None:
    rng = etree.RelaxNG(etree.parse(str(paths.SCHEMA / "edition.rng")))
    if not rng.validate(tree):
        errs = "\n".join(f"  line {e.line}: {e.message}" for e in list(rng.error_log)[:20])
        raise SystemExit(f"RELAX NG validation failed:\n{errs}")


def ingest_unit(unit: str, reg: Registry) -> dict:
    file, elements = epub.unit_range(unit)
    resp = epub.FRONT[unit][2] if epub.is_front(unit) else None
    div, ctx = convert.convert_unit(unit, file, elements, front=epub.is_front(unit), resp=resp)
    stats: Counter = Counter()
    stats.update(manual.apply(div, unit))
    stats.update(manual.apply_fixes(div, unit))
    stats.update(manual.apply_inline(div, unit))
    if resp != "#gowland":
        stats.update(gowland.separate(div))
    decisions = langid.run(div, unit, stats, gowland_unit=resp == "#gowland")
    ids = assign_ids(div, unit, reg)
    link_translations(div)
    review = [" ".join("".join(t.itertext()).split()) for t in gowland.trans_without_foreign(div)]
    retired = reg.finish_unit(unit)
    tree = wrap_document(div, unit, file)
    validate(tree)
    paths.TEXT.mkdir(parents=True, exist_ok=True)
    out = paths.TEXT / f"{unit}.xml"
    tmp = out.with_suffix(".tmp")
    tree.write(str(tmp), encoding="utf-8", xml_declaration=True)
    tmp.replace(out)
    mixed = langid.flag_mixed_script(div)
    report = {
        "unit": unit, "file": file, "elements": len(elements), "ids": dict(ids), "retired_ids": retired,
        "stats": dict(stats), "unknown_markup": dict(ctx.unknown),
        "trans_without_foreign": review, "mixed_script": mixed,
        "langid_decisions": decisions,
    }
    rep = paths.STATE / "ingest" / f"{unit}.json"
    rep.parent.mkdir(parents=True, exist_ok=True)
    rep.write_text(json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return report


def ingest(units: list[str], quiet: bool = False) -> None:
    check_lock()
    reg = Registry()
    for unit in units:
        r = ingest_unit(unit, reg)
        if quiet:
            continue
        s = r["stats"]
        print(f"{unit}: {r['elements']} source blocks -> data/text/{unit}.xml (valid)")
        print("  ids:", ", ".join(f"{k}={v}" for k, v in sorted(r["ids"].items())), f"retired={r['retired_ids']}")
        print("  gowland:", ", ".join(f"{k}={v}" for k, v in sorted(s.items())
                                      if k.startswith(("trans", "supplied", "verse"))))
        print("  language:", ", ".join(f"{k}={v}" for k, v in sorted(s.items())
                                       if k.startswith(("script", "lg", "italic"))))
        print(f"  review: {len(r['trans_without_foreign'])} bracket(s) not after a foreign passage; "
              f"{len(r['mixed_script'])} mixed-script join(s); unknown markup {r['unknown_markup'] or 'none'}")
    reg.save()
